import fs from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
import { chromium } from 'playwright-core';

const base='http://127.0.0.1:8766', out=path.resolve('audit/browser-research-loop');
await fs.mkdir(out,{recursive:true});
const browser=await chromium.launch({executablePath:'/usr/bin/google-chrome',headless:true,args:['--no-sandbox','--disable-dev-shm-usage','--disable-gpu']});
const page=await browser.newPage({viewport:{width:1440,height:1000}}), errors=[], checks=[];
page.on('pageerror',e=>errors.push(e.message));
page.on('console',m=>{if(m.type()==='error')errors.push(m.text())});
try {
 await page.goto(base,{waitUntil:'networkidle'});
 const get=async p=>(await page.request.get(base+p)).json();
 assert.equal((await get('/api/status')).gateway.requested_model,'SYNTHETIC TRANSPORT');
 const projects=await get('/api/workspaces'), wid=projects[0].id;
 await page.evaluate(id=>localStorage.setItem('evida-project',id),wid);
 await page.reload({waitUntil:'networkidle'});
 await page.locator('[data-action="run-check"]').click();
 await page.waitForFunction(()=>document.body.innerText.includes('실제 물성 계산이 완료되었습니다.'),null,{timeout:30000});
 let state=await get(`/api/workspaces/${wid}`);
 assert.equal(state.research_checks.length,1);
 assert.equal(state.jobs.filter(j=>j.kind==='rdkit').length,1);
 assert.equal(state.jobs.filter(j=>j.status!=='succeeded').length,0);
 checks.push('Click next check → actual RDKit worker → synthetic model review → persisted decision.');
 await page.locator('.hypothesis>summary').click();
 await page.locator('[data-action="hypothesis-feedback"]').click();
 await page.locator('#feedback-text').fill('가상 확인: 원래 입력 구조 식별에 정정이 필요합니다.');
 await page.locator('#feedback-comparison').selectOption('different');
 await page.locator('#feedback-synthetic').check();
 await page.locator('[data-action="save-feedback"][data-review="true"]').click();
 await page.waitForFunction(()=>document.body.innerText.includes('가상 전송 확인: 새 관측을 검토했습니다.'),null,{timeout:30000});
 state=await get(`/api/workspaces/${wid}`);
 const event=state.events.filter(e=>e.kind==='observation').at(-1);
 assert.equal(event.body.origin,'synthetic');
 assert.deepEqual(event.body.research_context.hypothesis_ids,['h1']);
 assert.equal(event.body.research_context.comparison,'different');
 assert.equal(state.decision.research_loop.hypotheses[0].assessment,'challenged');
 checks.push('Connected contradictory synthetic observation survives save and triggers explicit review.');
 await page.screenshot({path:path.join(out,'desktop-fixture.png'),fullPage:true});
 await page.reload({waitUntil:'networkidle'});
 assert.ok((await page.locator('body').innerText()).includes('다시 검토할 근거 있음'));
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:path.join(out,'mobile-fixture.png'),fullPage:true});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 checks.push('Persisted decision reloads; mobile page has no horizontal overflow.');
 assert.deepEqual(errors,[]);
 await fs.writeFile(path.join(out,'result.json'),JSON.stringify({mode:'test_fixture_no_live_model',checks,errors},null,2));
 console.log(JSON.stringify({passed:true,checks,out}));
} finally {await browser.close()}
