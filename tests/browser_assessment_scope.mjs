import fs from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
import { chromium } from 'playwright-core';

const base='http://127.0.0.1:8767', out=path.resolve('audit/browser-assessment-scope');
await fs.mkdir(out,{recursive:true});
const browser=await chromium.launch({executablePath:'/usr/bin/google-chrome',headless:true,args:['--no-sandbox','--disable-dev-shm-usage','--disable-gpu']});
const page=await browser.newPage({viewport:{width:1440,height:1000}}), errors=[], checks=[];
page.on('pageerror',e=>errors.push(e.message));
try {
 const get=async p=>(await page.request.get(base+p)).json();
 await page.goto(base,{waitUntil:'networkidle'});
 assert.equal((await get('/api/status')).gateway.requested_model,'SYNTHETIC TRANSPORT');
 const wid=(await get('/api/workspaces'))[0].id;
 await page.evaluate(id=>localStorage.setItem('evida-project',id),wid);
 await page.reload({waitUntil:'networkidle'});
 await page.locator('[data-action="run-check"]').click();
 await page.waitForFunction(()=>document.body.innerText.includes('실제 물성 계산이 완료되었습니다.'),null,{timeout:30000});
 const before=await get(`/api/workspaces/${wid}`);
 assert.equal(before.jobs.filter(j=>j.kind==='rdkit'&&j.status==='succeeded').length,1);
 await page.locator('.hypothesis>summary').click();
 assert.equal(await page.locator('[data-hypothesis-part]').count(),2);
 await page.locator('[data-action="hypothesis-feedback"][data-part="identity"]').click();
 assert.ok((await page.locator('dialog').innerText()).includes('sample identity differs'));
 assert.ok(!(await page.locator('dialog').innerText()).includes('measurement stage differs'));
 await page.locator('#feedback-text').fill('Synthetic correction to identity only; no stage observation.');
 await page.locator('#feedback-synthetic').check();
 await page.locator('#feedback-kind').selectOption('correction');
 await page.locator('[data-action="save-feedback"][data-review="false"]').click();
 await page.waitForFunction(()=>!document.querySelector('dialog').open);
 let state=await get(`/api/workspaces/${wid}`);
 const event=state.events.filter(e=>e.kind==='correction').at(-1);
 assert.deepEqual(event.body.research_context.scope_targets,[{hypothesis_id:'h1',part_ids:['identity']}]);
 assert.equal(event.body.research_context.decision_id,before.decision_id);
 assert.deepEqual(state.decision,before.decision);
 assert.equal(state.jobs.length,before.jobs.length);
 checks.push('Real RDKit result → synthetic reviewed scoped decision → identity-only correction persisted; no automatic review or relabeling.');
 await page.reload({waitUntil:'networkidle'});
 await page.locator('.hypothesis>summary').click();
 assert.ok((await page.locator('.hypothesis>summary').innerText()).includes('전체 판단: 다음 확인 필요'));
 await page.locator('[data-action="check-feedback"]').click();
 assert.ok((await page.locator('dialog').innerText()).includes('measurement stage differs'));
 await page.locator('#feedback-text').fill('Synthetic stage observation to test linked review.');
 await page.locator('#feedback-synthetic').check();
 await page.locator('[data-action="save-feedback"][data-review="true"]').click();
 await page.waitForFunction(()=>document.body.innerText.includes('가상 전송 확인: 새 관측을 검토했습니다.'),null,{timeout:30000});
 state=await get(`/api/workspaces/${wid}`);
 assert.deepEqual(state.events.filter(e=>e.kind==='observation').at(-1).body.research_context.scope_targets,[{hypothesis_id:'h1',part_ids:['stage']}]);
 assert.equal(state.decision_rev,state.rev);
 assert.equal(state.decision.research_loop.hypotheses[0].assessment_scope.parts[1].assessment,'inconclusive');
 checks.push('Scoped next-check observation → explicit synthetic review → updated decision, preserving the unresolved stage.');
 await page.locator('.hypothesis>summary').click();
 await page.screenshot({path:path.join(out,'desktop.png'),fullPage:true});
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:path.join(out,'mobile.png'),fullPage:true});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 assert.deepEqual(errors,[]);
 checks.push('Two parts and whole judgment visible on desktop and mobile; no overflow or script errors.');
 await fs.writeFile(path.join(out,'result.json'),JSON.stringify({mode:'synthetic_model_real_worker',checks,errors},null,2));
 console.log(JSON.stringify({passed:true,checks,out}));
} finally {await browser.close()}
